-- ---------------------------------------------------------------------
-- Admins
-- One row per Supabase Auth user. The Auth UUID is the primary key.
-- ---------------------------------------------------------------------
create table if not exists public.admins (
  id          uuid primary key references auth.users (id) on delete cascade,
  legacy_id   integer null,
  name        text not null,
  email       text unique not null,
  role        text not null default 'admin' check (role in ('super', 'admin')),
  last_login  timestamptz null,
  created_at  timestamptz not null default now()
);

comment on table public.admins is
  'Administrator accounts. Backed by Supabase Auth; id = auth.users.id.';

-- ---------------------------------------------------------------------
-- Participants
--
-- participant_seq is the single source of truth for the human readable
-- id. It comes from a PostgreSQL sequence, never from MAX(id) + 1, so
-- concurrent registrations can never collide.
-- ---------------------------------------------------------------------
create sequence if not exists public.participant_seq start 1;

create table if not exists public.participants (
  id              bigint generated by default as identity primary key,
  participant_id  text        not null unique,
  participant_seq bigint     not null unique,
  full_name       text        not null,
  email           text        not null,
  phone           text        not null,
  photo_path      text        null,
  flyer_path      text        null,
  qr_path         text        null,
  status          text        not null default 'registered'
                    check (status in ('registered', 'verified', 'cancelled')),
  ip_address      text        null,
  registered_at   timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

comment on column public.participants.participant_seq is
  'Value from public.participant_seq (PostgreSQL sequence). Never MAX(id)+1.';

comment on column public.participants.participant_id is
  'Human readable id, for example MIWC2026-000001. Derived from participant_seq.';

create index if not exists participants_email_idx
  on public.participants (lower(email));

create index if not exists participants_phone_idx
  on public.participants (phone);

create index if not exists participants_status_idx
  on public.participants (status);

create index if not exists participants_registered_idx
  on public.participants (registered_at desc);

-- Duplicate email guard (case-insensitive) at the database level.
create unique index if not exists participants_email_unique_idx
  on public.participants (lower(email));


-- ---------------------------------------------------------------------
