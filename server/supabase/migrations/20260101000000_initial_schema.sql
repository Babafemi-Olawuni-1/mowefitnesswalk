-- ---------------------------------------------------------------------
-- updated_at triggers
-- ---------------------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $fn$
begin
  new.updated_at = now();
  return new;
end;
$fn$;

drop trigger if exists participants_set_updated_at on public.participants;
create trigger participants_set_updated_at
  before update on public.participants
  for each row execute function public.set_updated_at();

drop trigger if exists sponsors_set_updated_at on public.sponsors;
create trigger sponsors_set_updated_at
  before update on public.sponsors
  for each row execute function public.set_updated_at();

drop trigger if exists contacts_set_updated_at on public.contacts;
create trigger contacts_set_updated_at
  before update on public.contacts
  for each row execute function public.set_updated_at();


-- =====================================================================
-- Row Level Security
--
-- The Node backend uses the service role key, which bypasses RLS.
-- The React app NEVER talks to Supabase directly.
--
-- Everything therefore defaults to deny. The only public reads are
-- genuinely public data: active sponsors, open event settings and active
-- gallery images. admins, participants, contacts and email_log have no
-- policies at all, so they are unreachable from any client key.
-- =====================================================================
alter table public.admins         enable row level security;
alter table public.participants   enable row level security;
alter table public.event_settings enable row level security;
alter table public.sponsors       enable row level security;
alter table public.gallery        enable row level security;
alter table public.contacts       enable row level security;
alter table public.email_log      enable row level security;

drop policy if exists sponsors_public_read on public.sponsors;
create policy sponsors_public_read
  on public.sponsors
  for select
  to anon, authenticated
  using (status = 'active');

drop policy if exists event_settings_public_read on public.event_settings;
create policy event_settings_public_read
  on public.event_settings
  for select
  to anon, authenticated
  using (registration_open = true);

drop policy if exists gallery_public_read on public.gallery;
create policy gallery_public_read
  on public.gallery
  for select
  to anon, authenticated
  using (status = 'active');
